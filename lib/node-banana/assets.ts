// The asset library shown in the Node Banana "Assets" demo: every still and
// clip here was made in Node Banana (the landing site's media and the shared
// car clips), recorded as the app's library records them (src/lib/assets/types.ts):
// what made it, with which model and settings, in which workflow and project.

export type AssetKind = "image" | "video" | "audio" | "3d";
export type AssetOrigin = "generated" | "edited" | "uploaded";
export type AssetProvider = "gemini" | "openai" | "fal" | "comfy";

export interface RunImage {
  src: string;
  width: number;
  height: number;
  filename: string;
  /** The original file's pixels, for the Image Input summary. */
  dimensions: { width: number; height: number };
}

/** The nodes that made an asset, for "Open workflow": its inputs and the node itself. */
export type AssetRun =
  | { type: "generateImage"; input?: RunImage }
  | { type: "generateVideo"; input?: RunImage }
  | { type: "comfy"; input?: RunImage }
  | { type: "splitGrid"; grid: RunImage }
  | { type: "easeCurve"; source: { src: string; poster: string; width: number; height: number; duration: number } };

export interface LibraryAsset {
  id: string;
  kind: AssetKind;
  origin: AssetOrigin;
  /** The tile's picture: the image itself, or a video's poster. */
  thumb?: { src: string; width: number; height: number };
  /** The playable file of a video or audio asset. */
  media?: string;
  /** The recorded file's pixels. */
  width?: number;
  height?: number;
  durationSec?: number;
  prompt?: string;
  filename: string;
  ext: string;
  mime: string;
  bytes: number;
  /** Minutes since Mon 26 Oct 2026 00:00, local: the sort key. */
  at: number;
  workflow: { id: string; name: string };
  /** The project folder, or null for "Not in a project". */
  project: string | null;
  producer: { type: string; title: string; operation?: string; batchIndex?: number };
  model?: { id: string; displayName: string; provider: AssetProvider };
  parameters?: Record<string, string | number | boolean>;
  cost?: { amount: number; estimated?: boolean };
  favorite?: boolean;
  tags?: string[];
  trashed?: boolean;
  /** Lands while the demo plays, in this order: a generation finishing elsewhere in the app. */
  arrival?: number;
  run?: AssetRun;
  /** Where the file is on disk. */
  path: string;
}

